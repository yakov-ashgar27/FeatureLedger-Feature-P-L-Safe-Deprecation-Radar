"""Evidence generators for the Safe Sunset pipeline (pure functions).

* blast_radius   - who still imports the feature's code (static import graph, metadata only)
* impact_dossier - paying accounts that used it in the lookback window, ARR-sorted, with a drafted
                   migration email per account for Customer Success to edit and send
* cleanup_pr     - outline of the dead-code PR: paths, routes, flag checks, tests, call sites
"""
from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass
from datetime import date
from typing import Any

from .manifest import FeatureSpec, Manifest, glob_to_regex


def _in_feature(path: str, spec: FeatureSpec) -> bool:
    return any(glob_to_regex(g).match(path) for g in spec.paths)


def blast_radius(spec: FeatureSpec, manifest: Manifest, edges: list[tuple[str, str]]) -> dict[str, Any]:
    """edges: (from_path, to_path) import edges across the org's repos."""
    inbound: dict[str, set[str]] = defaultdict(set)
    for src, dst in edges:
        if _in_feature(dst, spec) and not _in_feature(src, spec):
            inbound[src].add(dst)
    refs = []
    for src in sorted(inbound):
        refs.append({
            "from_path": src,
            "owner_feature": manifest.owner_of(src) or "unmapped",
            "imports": sorted(inbound[src]),
            "acknowledged": False,
        })
    by_owner: dict[str, int] = defaultdict(int)
    for r in refs:
        by_owner[r["owner_feature"]] += 1
    return {
        "feature": spec.key,
        "inbound_references": refs,
        "inbound_count": len(refs),
        "by_owner_feature": dict(sorted(by_owner.items(), key=lambda kv: -kv[1])),
        "api_routes": list(spec.api_routes),
        "flag_key": spec.flag_key,
        "risk": "low" if not refs else ("medium" if len(refs) <= 5 else "high"),
    }


@dataclass(frozen=True)
class DossierAccount:
    account_id: str
    name: str
    arr_usd: float
    plan_tier: str
    renewal_date: date | None
    feature_active_days_90d: int
    dependency_score: float
    churn_risk: float
    csm_email: str | None


def migration_email(feature_name: str, replacement: str | None, acct: DossierAccount, sunset_date: date) -> str:
    alt = (f"Everything you do with {feature_name} today is supported by {replacement}, and we will "
           f"migrate your existing configuration for you.") if replacement else (
           f"We would like to understand how your team uses {feature_name} so we can make sure "
           f"nothing in your workflow breaks.")
    usage = f"Your team used it on {acct.feature_active_days_90d} day(s) over the last 90 days."
    return (
        f"Subject: Changes to {feature_name} in your {acct.plan_tier.title()} workspace\n\n"
        f"Hi {acct.name} team,\n\n"
        f"We're retiring {feature_name} on {sunset_date:%B %d, %Y}. {usage} {alt}\n\n"
        f"Could we set up 20 minutes before then to walk through it together? Reply to this email "
        f"and I'll find a time that works.\n\nThanks,\n{(acct.csm_email or 'Your account team').split('@')[0]}"
    )


def impact_dossier(feature_name: str, replacement: str | None, accounts: list[DossierAccount],
                   sunset_date: date) -> dict[str, Any]:
    ordered = sorted(accounts, key=lambda a: (-a.arr_usd, a.name))
    return {
        "feature": feature_name,
        "replacement": replacement,
        "proposed_sunset_date": sunset_date.isoformat(),
        "accounts_affected": len(ordered),
        "arr_touched_usd": round(sum(a.arr_usd for a in ordered), 2),
        "arr_at_risk_usd": round(sum(a.arr_usd * a.churn_risk for a in ordered), 2),
        "accounts": [
            {
                "account_id": a.account_id, "name": a.name, "arr_usd": a.arr_usd, "plan_tier": a.plan_tier,
                "renewal_date": a.renewal_date.isoformat() if a.renewal_date else None,
                "feature_active_days_90d": a.feature_active_days_90d,
                "dependency_score": a.dependency_score, "churn_risk": a.churn_risk,
                "csm_email": a.csm_email, "acknowledged": False,
                "email_draft": migration_email(feature_name, replacement, a, sunset_date),
            }
            for a in ordered
        ],
    }


def cleanup_pr_outline(spec: FeatureSpec, br: dict[str, Any], known_files: list[str]) -> dict[str, Any]:
    owned = sorted(p for p in known_files if _in_feature(p, spec))
    tests = [p for p in owned if any(t in p for t in ("/test", "test_", ".test.", ".spec.", "__tests__"))]
    code = [p for p in owned if p not in tests]
    callers = [r["from_path"] for r in br.get("inbound_references", [])]
    title = f"chore(sunset): remove {spec.name} ({spec.key})"
    lines = [
        f"Removes **{spec.name}** after a clean scream test. Generated by FeatureLedger.",
        "",
        "### Delete",
        *[f"- [ ] `{p}`" for p in code],
        "",
        "### Delete tests",
        *([f"- [ ] `{p}`" for p in tests] or ["- [ ] (no tests found under the feature's paths)"]),
        "",
        "### Edit call sites (remove imports / dead branches)",
        *([f"- [ ] `{p}`" for p in callers] or ["- [ ] none: no inbound imports"]),
        "",
        "### Routes",
        *([f"- [ ] remove handler + OpenAPI entry for `{r}`" for r in spec.api_routes] or ["- [ ] none"]),
        "",
        "### Feature flag",
        (f"- [ ] remove all `{spec.flag_key}` checks, then archive the flag in the flag provider"
         if spec.flag_key else "- [ ] none"),
        "",
        "### Manifest",
        f"- [ ] delete the `{spec.key}` entry from `features.yaml` (FeatureLedger archives the feature on merge)",
    ]
    return {
        "title": title,
        "branch": f"featureledger/sunset-{spec.key}",
        "body_markdown": "\n".join(lines),
        "files_to_delete": code + tests,
        "files_to_edit": callers,
        "routes_to_remove": list(spec.api_routes),
        "flag_key": spec.flag_key,
    }
